/**
 * `as const` above keeps the source readable as data, but it also freezes every
 * value to its own literal type — a Spanish dictionary would then have to say
 * "Back" to satisfy it. Widening every leaf back to `string` gives the shape
 * without the literals, so a translation is checked for completeness and
 * structure and nothing else.
 */
type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> };

/** Every other language is checked against this. */
